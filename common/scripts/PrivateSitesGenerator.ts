import { transformVariableName } from "../src/utils.js";
import { parse } from "@babel/parser";
import traverse from "@babel/traverse";
import * as fs from "fs";
import * as http from "http";
import * as https from "https";

const scriptUrl =
  "https://raw.githubusercontent.com/Purfview/IMDb-Scout-Mod/master/IMDb_Scout_Mod.user.js";
let code: string = await new Promise((resolve, reject) => {
  https
    .get(scriptUrl, (response: http.IncomingMessage) => {
      if (response.statusCode !== 200) {
        reject(`Received status code: ${response.statusCode}`);
      }
      let data = "";
      response.on("data", (chunk: any) => (data += chunk));
      response.on("end", () => resolve(data));
    })
    .on("error", (err: Error) => {
      reject(err);
    });
});

const ast = parse(code, { sourceType: "script", errorRecovery: true });

let privateSitesConfig: PrivateSiteConfig[] = [];
const sites = [
  "private_sites",
  "chinese_sites",
  "french_sites",
  "german_sites",
];

traverse(ast, {
  VariableDeclaration(path) {
    for (const declaration of path.node.declarations) {
      if (!("name" in declaration.id)) continue;
      if (!declaration.init) continue;
      if (
        sites.includes(declaration.id.name as string) &&
        declaration.init.type === "ArrayExpression"
      ) {
        const sitesConfig = declaration.init.elements.map((element: any) => {
          if (element.type === "StringLiteral") {
            return element.value;
          } else if (element.type === "ObjectExpression") {
            let obj: PrivateSiteConfig = { name: "", searchUrl: "" };
            for (const property of element.properties) {
              if (property.type !== "ObjectProperty") continue;
              const key = (property.key as any).name ?? (property.key as any).value;
              let value: any;
              if (property.value.type === "RegExpLiteral") {
                value = new RegExp(property.value.pattern, property.value.flags);
              } else {
                value = (property.value as any).value;
              }
              obj[key] = value;
            }
            return obj;
          }
        });
        privateSitesConfig = privateSitesConfig.concat(sitesConfig);
      }
    }
  },
});

if (privateSitesConfig) {
  const excludeKeys = ["icon"];

  let output = `// FILE AUTOGENERATED\nexport type PrivateTracker = {
  name: string;
  TV?: boolean;
  searchUrl: string;
  mPOST?: string;
  spaceEncode?: string;
  [key: string]: boolean | string | RegExp | undefined | number;
};\n\n`;

  privateSitesConfig.sort((a, b) => {
    if (a.name < b.name) return -1;
    if (a.name > b.name) return 1;
    return 0;
  });

  for (const item of privateSitesConfig) {
    const itemName = item.name;
    let itemProps = "";

    for (const key in item) {
      if (!excludeKeys.includes(key)) {
        if (item[key] instanceof RegExp) {
          itemProps += `  ${key}: ${item[key]},\n`;
        } else if (
          typeof item[key] === "boolean" ||
          typeof item[key] === "number"
        ) {
          itemProps += `  ${key}: ${item[key]},\n`;
        } else {
          itemProps += `  ${key}: '${item[key]}',\n`;
        }
      }
    }

    let name = transformVariableName(itemName);
    if (item.TV) {
      name += "_TV";
    }
    output += `export const ${name}: PrivateTracker = {\n${itemProps}};\n\n`;
  }

  fs.writeFileSync("src/trackers/index.ts", output);
} else {
  console.log("Could not parse private sites config.");
}

type PrivateSiteConfig = {
  name: string;
  TV?: boolean;
  searchUrl: string;
  mPOST?: string;
  [key: string]: boolean | string | RegExp | undefined | number;
};
